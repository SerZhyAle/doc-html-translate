/* The help set's one script (CONTEXT-HELP rules 10 and 12). The pages are complete without it: it only follows the
   window's theme (?theme=light|dark), opens the entry a link or an F1 anchor points at, and links a pin to its entry.
   It makes no request. Generated by tools/helpgen; do not edit. */
(function () {
  try {
    var q = new URLSearchParams(location.search).get('theme');
    if (q === 'light' || q === 'dark') { document.documentElement.setAttribute('data-theme', q); }
  } catch (e) { /* no query: the stylesheet follows the system */ }

  function openHash() {
    var id = decodeURIComponent(location.hash.slice(1));
    var el = id && document.getElementById(id);
    if (el && el.tagName === 'DETAILS') { el.open = true; el.scrollIntoView({ block: 'center' }); }
  }
  function ready() {
    openHash();
    addEventListener('hashchange', openHash);
    document.querySelectorAll('details.el').forEach(function (d) {
      var pin = document.querySelector('.pin[href="#' + d.id + '"]');
      if (!pin) { return; }
      function on() { pin.classList.add('on'); d.classList.add('on'); }
      function off() { pin.classList.remove('on'); d.classList.remove('on'); }
      d.addEventListener('mouseenter', on); d.addEventListener('mouseleave', off);
      d.addEventListener('focusin', on); d.addEventListener('focusout', off);
      pin.addEventListener('mouseenter', on); pin.addEventListener('mouseleave', off);
      pin.addEventListener('focus', on); pin.addEventListener('blur', off);
    });
  }
  if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', ready); } else { ready(); }
})();
