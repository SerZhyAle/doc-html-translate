package commands

import (
	"fmt"
	"strings"
)

// Markdown renders docs/CLI.md from the manifest (APP-COMMANDS rule 20): the command table, then for each command its
// synopsis, options, data, risk, exit codes and examples. The page is a render target - tools/clidoc writes it and
// holds it byte for byte equal, so it is never edited by hand.
func Markdown(m *Manifest) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }

	w("<!-- Generated by tools/clidoc from docs/cli-commands.json (APP-COMMANDS rule 20). Do not edit by hand. -->\n\n")
	w("# %s command line\n\n", m.Product)
	w("Command set %s of `%s`. Scripts and agents drive the product by its command line. This page is rendered from the manifest [`cli-commands.json`](cli-commands.json), and `%s commands --json` prints the same manifest as data (APP-COMMANDS rules 18 and 20).\n\n", m.CLIVersion, m.Exe, m.Exe)
	w("The grammar is APP-COMMANDS rules 1 and 3: a verb of one or two lower-case words, then options written `--name`, `--name=value` or `--name value`; `--` ends the options; verbs and options are compared without regard to case, values never. An unknown verb, an unknown option, a missing value or a value of the wrong kind exits 10 and runs nothing. A command line is at most 64 KiB and one argument at most 32 KiB; more is refused, never cut.\n\n")
	w("The conversion call `%s [flags] <path>` keeps its own flags and exit codes: [`../README.md`](../README.md) lists the flags and `OCR-INVOCATION` section D the exit codes.\n\n", m.Exe)

	w("## Commands\n\n")
	w("| Command | Aliases | Summary | Risk | Cold start |\n| --- | --- | --- | --- | --- |\n")
	for _, c := range m.Commands {
		w("| [`%s`](#%s) | %s | %s | `%s` | `%s` |\n", c.Name, anchor(c.Name), codeList(aliasSpellings(c.Aliases)), cell(c.Summary), c.Risk, c.ColdStart)
	}
	w("\n")

	for _, c := range m.Commands {
		w("## `%s`\n\n", c.Name)
		w("%s\n\n", c.Summary)
		w("```text\n%s\n```\n\n", c.Synopsis)
		w("- **Risk:** `%s` - **cold start:** `%s` - **wait:** `%s` - **time bound:** %s - **idempotent:** %s - **since:** %s\n", c.Risk, c.ColdStart, c.Wait, timeout(c), yesNo(c.Idempotent), c.Since)
		if c.Exe != "" {
			w("- **Executable:** `%s`\n", c.Exe)
		}
		if c.Forward == "never" {
			w("- **Forward:** `never` (the process that receives the command does the work itself)\n")
		} else if c.Forward == "always" {
			w("- **Forward:** `always` (forwarded to the running first instance over the local command pipe)\n")
		}
		if al := aliasSpellings(c.Aliases); len(al) > 0 {
			w("- **Frozen aliases:** %s\n", codeList(al))
		}
		if c.DefaultFor != "" {
			w("- **Default verb of `%s`:** a command line with no verb word, a path and flags, is this verb\n", c.DefaultFor)
		}
		w("\n")
		if len(c.Args) > 0 {
			w("Options:\n\n| Option | Kind | Required | Default | Description |\n| --- | --- | --- | --- | --- |\n")
			for _, a := range c.Args {
				name := "--" + a.Name
				if a.Positional {
					name = "<" + a.Name + ">"
				}
				if len(a.Aliases) > 0 {
					name += " (alias -" + strings.Join(a.Aliases, ", -") + ")"
				}
				kind := a.Kind
				if a.Kind == "enum" {
					kind += ": " + strings.Join(a.Values, " ")
				}
				w("| `%s` | %s | %s | %s | %s |\n", name, cell(kind), yesNo(a.Required), def(a), cell(a.Description))
			}
			w("\n")
		}
		if len(c.Returns) > 0 {
			w("Data:\n\n| Key | Kind | Description |\n| --- | --- | --- |\n")
			for _, r := range c.Returns {
				w("| `%s` | %s | %s |\n", r.Name, r.Kind, cell(r.Description))
			}
			w("\n")
		}
		w("Exit codes:\n\n| Code | Meaning |\n| --- | --- |\n")
		for _, e := range c.ExitCodes {
			w("| %d | %s |\n", e.Code, cell(e.Meaning))
		}
		w("\n")
		w("Examples:\n\n")
		for _, e := range c.Examples {
			w("```%s\n%s\n```\n\nExpected: %s\n\n", e.Shell, e.Line, e.Expect)
		}
		if c.Notes != "" {
			w("%s\n\n", c.Notes)
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// anchor is the GitHub heading anchor of "## `name`": lower-case, spaces become hyphens.
func anchor(name string) string { return strings.ReplaceAll(name, " ", "-") }

// cell makes text safe inside a table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(s, "|", `\|`), "\n", " ")
}

func codeList(items []string) string {
	var out []string
	for _, s := range items {
		if s != "" {
			out = append(out, "`"+s+"`")
		}
	}
	if len(out) == 0 {
		return "-"
	}
	return strings.Join(out, " ")
}

func aliasSpellings(aliases []Alias) []string {
	var out []string
	for _, a := range aliases {
		if a.Spelling != "" {
			out = append(out, a.Spelling)
		}
	}
	return out
}

func yesNo(p *bool) string {
	if p != nil && *p {
		return "yes"
	}
	return "no"
}

func timeout(c Command) string {
	if c.TimeoutMs == nil {
		return "-"
	}
	if *c.TimeoutMs == 0 {
		return "none of its own"
	}
	return fmt.Sprintf("%d ms", *c.TimeoutMs)
}

func def(a Arg) string {
	if len(a.Default) == 0 {
		return "-"
	}
	return "`" + string(a.Default) + "`"
}
